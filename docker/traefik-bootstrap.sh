#!/bin/sh
# Writes the app route (APP_HOST) into Traefik's dynamic directory once Traefik
# is reachable, then exits. The file provider cannot interpolate ${APP_HOST},
# so this bridges .env and the routing table.
#
# The directory is loaded wholesale by Traefik: one invalid file breaks every
# route, so the generated YAML is kept minimal and schema-valid.
set -e

: "${APP_HOST:?APP_HOST is required}"
: "${TLS_ENABLED:=true}"
: "${DYNAMIC_DIR:=/etc/traefik/dynamic}"
: "${TRAEFIK_API_HOST:=traefik:8080}"

echo "==> Waiting for the Traefik API (${TRAEFIK_API_HOST})"
i=0
until curl -fsS "http://${TRAEFIK_API_HOST}/api/overview" >/dev/null 2>&1; do
  i=$((i + 1))
  if [ "$i" -gt 180 ]; then
    echo "    Traefik API not reachable after 3 minutes — the app route was NOT applied" >&2
    exit 1
  fi
  sleep 1
done

if [ "$TLS_ENABLED" = "true" ]; then
  echo "==> Writing app route (https): ${APP_HOST}"
  cat > "${DYNAMIC_DIR}/petbug-app.yaml" <<EOF
# Generated by route-sync from APP_HOST / TLS_ENABLED — do not edit.
http:
  routers:
    petbug-app:
      rule: "Host(\`${APP_HOST}\`)"
      entryPoints:
        - web
      middlewares:
        - lab-redirect-https
      service: petbug-web
      priority: 500
    petbug-app-tls:
      rule: "Host(\`${APP_HOST}\`)"
      entryPoints:
        - websecure
      middlewares:
        - secure-headers
      service: petbug-web
      priority: 500
      tls:
        certResolver: le
EOF
else
  echo "==> Writing app route (http): ${APP_HOST}"
  cat > "${DYNAMIC_DIR}/petbug-app.yaml" <<EOF
# Generated by route-sync from APP_HOST / TLS_ENABLED — do not edit.
http:
  routers:
    petbug-app:
      rule: "Host(\`${APP_HOST}\`)"
      entryPoints:
        - web
      service: petbug-web
      priority: 500
EOF
fi

echo "    wrote ${DYNAMIC_DIR}/petbug-app.yaml"

# Give the file provider a moment to pick the file up, then verify the router is live.
sleep 3
if curl -fsS "http://${TRAEFIK_API_HOST}/api/http/routers" 2>/dev/null | grep -q 'petbug-app'; then
  echo "    app router is live"
else
  echo "    WARN: router not visible yet — the provider may still be reloading" >&2
fi
